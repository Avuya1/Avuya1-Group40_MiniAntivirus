    //Scan folders button
    private void jButtonScanFolderActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButtonScanFolderActionPerformed
        // TODO add your handling code here:
        
        if (selectedFolder == null) {
            javax.swing.JOptionPane.showMessageDialog(this, "Please choose a folder first.");
            return;
        }
        
        if (!selectedFolder.exists() || !selectedFolder.isDirectory()) {
            javax.swing.JOptionPane.showMessageDialog(this,"The selected folder is no longer available.");
            return;
        }
        
        // Count files using ScannerService
        int totalFiles = scannerService.countFiles(selectedFolder);
        jLabelFilesFound.setText("Files Found: " + totalFiles);

        // Find suspicious files using ScannerService
        List<File> suspiciousFiles = scannerService.findSuspiciousFiles(selectedFolder);
        jLabelThreatsFound.setText("Threats Found: " + suspiciousFiles.size());

        // Create scan report
        StringBuilder results = new StringBuilder();
        results.append("SCAN RESULTS\n");
        results.append("==============================\n");
        results.append("Folder: ")
                .append(selectedFolder.getAbsolutePath())
                .append("\n\n");
        
        results.append("Files scanned: ")
                .append(totalFiles)
                .append("\n");

        results.append("Suspicious files found: ")
                .append(suspiciousFiles.size())
                .append("\n\n");


        if (suspiciousFiles.isEmpty()) {
            results.append("No files matched the current detection rules.\n");
        } else {
            for (File file : suspiciousFiles) {

                results.append("SUSPICIOUS FILE\n");
                results.append("Name: ")
                        .append(file.getName())
                        .append("\n");

                results.append("Path: ")
                        .append(file.getAbsolutePath())
                        .append("\n");

                String fileName =
                        file.getName().toLowerCase(java.util.Locale.ROOT);

               String reason = scannerService.checkFile(file);

                results.append("Reason: ")
                        .append(reason)
                        .append("\n");
            }
        }
        
        results.append("Scan completed.");

        // Display results
        jTextPaneActivityLog.setText(results.toString());
        // Activity log
        addLog("SCAN OPERATION");
        addLog("Folder: " + selectedFolder.getAbsolutePath());
        addLog("Files scanned: " + totalFiles);
        addLog("Suspicious files found: "
                + suspiciousFiles.size());
        addLog("Status: Completed");
        addLog("------------------------------");
    }//GEN-LAST:event_jButtonScanFolderActionPerformed

    private void jButtonQuarantineFilesActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButtonQuarantineFilesActionPerformed
        // TODO add your handling code here:
        
        if (selectedFolder == null) {
            javax.swing.JOptionPane.showMessageDialog(this,"Please choose and scan a folder first.");
            return;
        }

        // Find suspicious files
        List<File> suspiciousFiles = scannerService.findSuspiciousFiles(selectedFolder);

        if (suspiciousFiles.isEmpty()) {
            
            javax.swing.JOptionPane.showMessageDialog(this,"No suspicious files were found.");
            return;
        }

        originalFolder = selectedFolder;
        // Create quarantine folder
        quarantineFolder = new File(selectedFolder.getParentFile(),"SecureByte_Quarantine");
        
        if (!quarantineFolder.exists()) {
            quarantineFolder.mkdirs();
        }

        // Move files using QuarantinedFiles class
        int movedCount = quarantineService.quarantineFiles(selectedFolder, quarantineFolder, suspiciousFiles);

        
        updateQuarantinedFilesList();
        
        // Update threats counter
        jLabelThreatsFound.setText("Threats Found: 0");

        // Record activity
        addLog("Quarantine operation completed.");
        addLog("Files moved: " + movedCount);

        javax.swing.JOptionPane.showMessageDialog(this,movedCount + " file(s) moved to quarantine.");
        
    }//GEN-LAST:event_jButtonQuarantineFilesActionPerformed

    private void jButtonRemoveFilesActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButtonRemoveFilesActionPerformed
        // TODO add your handling code here:
        if (quarantineFolder == null || !quarantineFolder.exists()) {
            javax.swing.JOptionPane.showMessageDialog(this,"No quarantined files found.");
            return;
        }

        // Ask for confirmation
        int choice = javax.swing.JOptionPane.showConfirmDialog(this,
            "Are you sure you want to permanently remove these files?",
            "Remove Files",
            javax.swing.JOptionPane.YES_NO_OPTION);
        
        if (choice == javax.swing.JOptionPane.YES_OPTION) {

            // Remove files using QuarantinedFiles class
            int removed = quarantineService.removeFiles(quarantineFolder);

            // Update the text pane
            updateQuarantinedFilesList();
            // Write to activity log
            addLog("Quarantined files removed: " + removed);

            javax.swing.JOptionPane.showMessageDialog(this,removed + " file(s) removed.");
        }
        
    }//GEN-LAST:event_jButtonRemoveFilesActionPerformed

    private void jButtonRemoveFiles1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButtonRemoveFiles1ActionPerformed
        // TODO add your handling code here:
        
    // Check if a file is selected
    int selectedIndex = jListQuarantinedFiles.getSelectedIndex();

    if (selectedIndex == -1) {
        javax.swing.JOptionPane.showMessageDialog(this,
                "Please select a file to restore.");
        return;
    }

    // Get the selected file
    File selectedFile = quarantinedFileList.get(selectedIndex);

    // Check if the original folder is available
    if (originalFolder == null) {
        javax.swing.JOptionPane.showMessageDialog(this,
                "Original folder is not available.");
        return;
    }

    // Restore the file
    boolean restored = quarantineService.restoreFile(
            originalFolder, quarantineFolder, selectedFile);

    if (restored) {

        updateQuarantinedFilesList();

        addLog("File restored: " + selectedFile.getName());

        javax.swing.JOptionPane.showMessageDialog(this,
                "File restored successfully.");

    } else {

        javax.swing.JOptionPane.showMessageDialog(this,
                "Could not restore file. A file with the same name may already exist.");
    }

    }//GEN-LAST:event_jButtonRemoveFiles1ActionPerformed

    //Calculate SHA button
    private void jButton7ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton7ActionPerformed
        // TODO add your handling code here:
     JFileChooser chooser = new JFileChooser();

    int result = chooser.showOpenDialog(this);

    if (result == JFileChooser.APPROVE_OPTION) {

        File selectedFile = chooser.getSelectedFile();

        hashingService = new FileHashing(selectedFile);

        try {
            String hash = hashingService.calculateHash();

            javax.swing.JOptionPane.showMessageDialog(
                this,
                "File: " + selectedFile.getName()
                + "\n\nSHA-256 Hash:\n" + hash,
                "File Hash Result",
                javax.swing.JOptionPane.INFORMATION_MESSAGE
            );

            addLog("SHA-256 hash calculated for: " + selectedFile.getName());

        } catch (IOException exception) {

            javax.swing.JOptionPane.showMessageDialog(
                this,
                "Could not calculate file hash.",
                "Hashing Error",
                javax.swing.JOptionPane.ERROR_MESSAGE
            );
        }
    }
    }//GEN-LAST:event_jButton7ActionPerformed

